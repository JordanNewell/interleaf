const RESERVED_SET = new Set(RESERVED_ADDRESSES);

/**
 * Case-insensitive and token-aware: §2 permits capitals and separators in
 * addresses, but a reserved name in any casing — or riding as one token of a
 * composed handle — is still a reserved name.
 */
export function isReservedAddress(address: string): boolean {
  const norm = address.trim().toLowerCase();
  if (norm === "") return false;
  if (RESERVED_SET.has(norm)) return true;
  const tokens = norm.split(/[._-]+/);
  return tokens.some((t) => t !== "" && RESERVED_SET.has(t));
}
