/**
 * Reserved addresses (SPEC §2): names that sound like the bus itself, an
 * authority speaking with official weight, or an institution whose trust a
 * stranger must never be able to borrow. No participant may register one as
 * its own address — onboarding, the settings identity field, contact
 * adding, contact-import suggestions, and the agent API all refuse —
 * because `from` is self-declared (§8) and mail from "support",
 * "paypal-support", or "cloudflare-security" must never get to look
 * ordinary.
 *
 * The list runs to hundreds of names across weight tiers: system &
 * infrastructure, corporate roles, finance (banks, cards, payment apps,
 * crypto), government/law/emergency (international numbers included),
 * political titles, news brands, big tech and AI labs, cloud/dev/security
 * vendors, Fortune-500-scale consumer brands, academia (institutions *and*
 * the administrative offices scammers impersonate — admissions, registrar,
 * financial-aid), religious titles and institutions, the most-impersonated
 * public figures and athletes, and the phrases fake authority always says
 * (lottery, verify, seed-phrase). People are reserved by full distinctive
 * name plus unmistakable bare surname (musk, trump, messi) — never by
 * common given names: muhammad, jesus, ali, jordan, and drake are real
 * people's names and stay registrable. Some entries are ordinary words a
 * brand happens to own (target, chase, shell, ice); they are reserved
 * anyway — anti-spoof errs closed, and the cost of a false positive is
 * picking another handle while the cost of a miss is a convincing
 * impersonation.
 *
 * Matching is by §2 token: a name is reserved when the whole name is on
 * the list OR any of its `.`/`_`/`-`-separated tokens is ("admin-team",
 * "paypal.support", "google-recruit" all reject). An address that already
 * held a newly-reserved name before an upgrade is grandfathered:
 * enforcement refuses *changes to* a reserved name, never strips an
 * existing identity.
 *
 * Mail that *arrives* carrying a reserved name (a script can still append
 * it; §8 as ever) renders behind a spoof warning instead. This is
 * anti-spoof hygiene in the reference UI, not authentication —
 * cryptographic identity stays with the OM-2 layer. The list is data, not
 * logic: trimming or extending it is a one-line edit here, and every entry
 * must stay a valid §2 address (the unit suite enforces shape, lowercase,
 * and uniqueness).
 */

